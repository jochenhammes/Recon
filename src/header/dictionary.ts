export interface DictEntry {
  vr: string;
  /** Human-readable name derived from the keyword ("PatientName" → "Patient Name"). */
  name: string;
}

const DICT = new Map<string, DictEntry>(
  ENTRIES.map(([tag, vr, keyword]) => [
    `x${tag.toLowerCase()}`,
    { vr, name: keyword.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/([A-Z])([A-Z][a-z])/g, "$1 $2") },
  ]),
);

/** Looks up a dicom-parser tag key ("xGGGGEEEE"). Group-length and private tags get generic names. */
export function lookupTag(tag: string): DictEntry | undefined {
  const hit = DICT.get(tag);
  if (hit) return hit;
  const group = parseInt(tag.slice(1, 5), 16);
  const element = parseInt(tag.slice(5), 16);
  if (element === 0) return { vr: "UL", name: "Group Length" };
  if (group % 2 === 1) return { vr: element >= 0x0010 && element <= 0x00ff ? "LO" : "UN", name: element <= 0x00ff ? "Private Creator" : "Private Tag" };
  return undefined;
}

/** "x00100010" → "(0010,0010)" */
export function formatTag(tag: string): string {
  return `(${tag.slice(1, 5).toUpperCase()},${tag.slice(5).toUpperCase()})`;
}

/** "0010,0010", "(0010,0010)" or "00100010" → "x00100010", or null if invalid. */
export function parseTag(input: string): string | null {
  const hex = input.replace(/[()\s,]/g, "");
  return /^[0-9a-fA-F]{8}$/.test(hex) ? `x${hex.toLowerCase()}` : null;
}
